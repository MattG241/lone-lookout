#!/usr/bin/env python3
"""
build_assets.py -- generate every runtime asset into gen/ for the Makefile.

Outputs (all deterministic, rewritten only when their bytes change):
    gen/*.bin            GX-tiled textures, embedded into the .dol via bin2o
    gen/assets.h         symbol declarations, sizes and formats
    gen/palette_data.h   colour script from data/palette/time_of_day.json
    gen/font_*.h         Lookout Hand glyph metrics
    gen/world_*.bin      the baked Ashen Peaks (heights, colours, surfaces, foliage)
    gen/world_data.h     map constants, places, trails (tools/worldgen/bake_world.py)
    gen/assets.mk        list of generated binaries (included by the Makefile)

Usage:  python3 tools/assets/build_assets.py gen
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools", "font"))
sys.path.insert(0, os.path.join(ROOT, "tools", "worldgen"))
sys.path.insert(0, os.path.join(ROOT, "tools", "dialogue"))
sys.path.insert(0, os.path.join(ROOT, "tools", "music"))

import numpy as np  # noqa: E402

import gxtex  # noqa: E402
import textures  # noqa: E402
import lookout_hand  # noqa: E402
import bake_world  # noqa: E402
import compile_lls  # noqa: E402
import compile_music  # noqa: E402

FMT_NAMES = {gxtex.GX_TF_I4: "GX_TF_I4", gxtex.GX_TF_I8: "GX_TF_I8", gxtex.GX_TF_IA4: "GX_TF_IA4",
             gxtex.GX_TF_IA8: "GX_TF_IA8", gxtex.GX_TF_RGB565: "GX_TF_RGB565",
             gxtex.GX_TF_RGB5A3: "GX_TF_RGB5A3", gxtex.GX_TF_RGBA8: "GX_TF_RGBA8"}


def write_if_changed(path, data):
    mode = "wb" if isinstance(data, (bytes, bytearray)) else "w"
    if os.path.exists(path):
        with open(path, "rb") as f:
            old = f.read()
        new = data if isinstance(data, (bytes, bytearray)) else data.encode()
        if old == new:
            return False
    with open(path, mode) as f:
        f.write(data)
    return True


def hexrgb(s):
    s = s.lstrip("#")
    return [int(s[i:i + 2], 16) / 255.0 for i in (0, 2, 4)]


def palette_header():
    with open(os.path.join(ROOT, "data", "palette", "time_of_day.json")) as f:
        pal = json.load(f)
    out = ["/* Generated from data/palette/time_of_day.json -- do not edit. */",
           "#ifndef LL_PALETTE_DATA_H", "#define LL_PALETTE_DATA_H", "",
           "typedef struct {",
           "  float time;",
           "  float sky_top[3], sky_horizon[3], fog[3], sun[3], shadow[3], ambient[3];",
           "  float key_strength, sun_elev, fog_density, window_glow;",
           "} ll_palkey;", "",
           f"#define PAL_NUM_KEYS {len(pal['keyframes'])}",
           "static const ll_palkey PAL_KEYS[PAL_NUM_KEYS] = {"]

    def v3(c):
        r, g, b = hexrgb(c)
        return f"{{{r:.4f}f,{g:.4f}f,{b:.4f}f}}"

    for k in pal["keyframes"]:
        out.append(f"  {{ {k['time']:.2f}f, {v3(k['sky_top'])}, {v3(k['sky_horizon'])}, {v3(k['fog'])}, "
                   f"{v3(k['sun'])}, {v3(k['shadow'])}, {v3(k['ambient'])}, "
                   f"{k['key_strength']:.3f}f, {k['sun_elev']:.1f}f, {k['fog_density']:.3f}f, "
                   f"{k['window_glow']:.3f}f }}, /* {k['name']} */")
    out.append("};")
    out.append("")
    for name, c in pal["albedo"].items():
        out.append(f"static const float ALB_{name.upper()}[3] = {v3(c)};")
    for name, c in pal["ui"].items():
        out.append(f"static const float UI_{name.upper()}[3] = {v3(c)};")
    g = pal["grade"]
    out += ["", f"static const float GRADE_LIFT[3] = {v3(g['lift'])};",
            f"#define GRADE_LIFT_AMOUNT {g['lift_amount']:.3f}f",
            f"static const float GRADE_TINT[3] = {v3(g['tint'])};",
            f"#define GRADE_GRAIN {g['grain']:.3f}f",
            f"#define GRADE_VIGNETTE {g['vignette']:.3f}f",
            "", "#endif", ""]
    return "\n".join(out)


def main():
    out_dir = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "gen"))
    os.makedirs(out_dir, exist_ok=True)
    changed = []
    bins = []
    decl = ["/* Generated by tools/assets/build_assets.py -- do not edit. */",
            "#ifndef LL_ASSETS_H", "#define LL_ASSETS_H", "#include <gctypes.h>", ""]

    def emit_tex(name, w, h, fmt, data):
        fn = f"{name}.bin"
        if write_if_changed(os.path.join(out_dir, fn), data):
            changed.append(fn)
        bins.append(fn)
        decl.extend([f'#include "{name}_bin.h"   /* from bin2o: {name}_bin[], {name}_bin_size */',
                     f"#define {name.upper()}_W {w}",
                     f"#define {name.upper()}_H {h}",
                     f"#define {name.upper()}_FMT {FMT_NAMES[fmt]}", ""])

    emit_tex("tex_paper", 256, 256, gxtex.GX_TF_I8, gxtex.encode_i8(textures.paper_detail()))
    emit_tex("tex_grain", 128, 128, gxtex.GX_TF_I8, gxtex.encode_i8(textures.grain()))
    emit_tex("tex_glow", 64, 64, gxtex.GX_TF_I8, gxtex.encode_i8(textures.glow()))
    fi, fa = textures.foliage_atlas()
    emit_tex("tex_foliage", textures.ATLAS_W, textures.ATLAS_H, gxtex.GX_TF_IA8, gxtex.encode_ia8(fi, fa))
    bi, ba = textures.backdrop_layers()
    emit_tex("tex_backdrop", bi.shape[1], bi.shape[0], gxtex.GX_TF_IA4, gxtex.encode_ia4(bi, ba))

    # The world: heights, colours, surfaces and foliage, plus the notebook map.
    blobs, world_h, map_rgb, stats = bake_world.build()
    for name, data in blobs:
        fn = f"{name}.bin"
        if write_if_changed(os.path.join(out_dir, fn), data):
            changed.append(fn)
        bins.append(fn)
        decl.append(f'#include "{name}_bin.h"   /* from bin2o: {name}_bin[], {name}_bin_size */')
    decl.append("")
    if write_if_changed(os.path.join(out_dir, "world_data.h"), world_h):
        changed.append("world_data.h")
    emit_tex("tex_map", map_rgb.shape[1], map_rgb.shape[0], gxtex.GX_TF_RGB565, gxtex.encode_rgb565(map_rgb))

    decl.append("/* Foliage atlas cells (pixels): x, y, w, h */")
    for i, (cell, (x, y, w, h)) in enumerate(textures.ATLAS_CELLS.items()):
        decl.append(f"#define ATLAS_{cell.upper()} {x},{y},{w},{h}")
    decl.append("#define BACKDROP_LAYER_H 64")
    decl.append("")

    # Fonts: small (subtitles, UI) and large (titles, notes).
    fonts = [("font_small", 1.9, 512, 256), ("font_large", 3.3, 1024, 512)]
    for name, scale, aw, ah in fonts:
        atlas, table, metrics = lookout_hand.build_atlas(scale, aw, ah)
        emit_tex(name, aw, ah, gxtex.GX_TF_I4, gxtex.encode_i4(atlas))
        if write_if_changed(os.path.join(out_dir, f"{name}.h"),
                            lookout_hand.c_table(name, table, metrics, aw, ah)):
            changed.append(f"{name}.h")
    if write_if_changed(os.path.join(out_dir, "font_slots.h"), lookout_hand.c_slot_map()):
        changed.append("font_slots.h")

    # The radio script.
    try:
        flags_h, data_h, dstats = compile_lls.compile_dir(os.path.join(ROOT, "data", "dialogue"))
    except compile_lls.LlsError as e:
        print(f"dialogue: {e}", file=sys.stderr)
        sys.exit(1)
    for name, text in (("dialogue_flags.h", flags_h), ("dialogue_data.h", data_h), ("vo_lines.txt", dstats["vo"])):
        if write_if_changed(os.path.join(out_dir, name), text):
            changed.append(name)

    # The music.
    try:
        music_h, mstats = compile_music.compile_dir(os.path.join(ROOT, "data", "music"))
    except compile_music.ScoreError as e:
        print(f"music: {e}", file=sys.stderr)
        sys.exit(1)
    if write_if_changed(os.path.join(out_dir, "music_data.h"), music_h):
        changed.append("music_data.h")

    decl += ["#endif", ""]
    if write_if_changed(os.path.join(out_dir, "assets.h"), "\n".join(decl)):
        changed.append("assets.h")
    if write_if_changed(os.path.join(out_dir, "palette_data.h"), palette_header()):
        changed.append("palette_data.h")
    mk = "# Generated by tools/assets/build_assets.py\nGEN_BINS := " + " ".join(bins) + "\n"
    write_if_changed(os.path.join(out_dir, "assets.mk"), mk)
    print(f"assets: {len(bins)} binaries, {stats['trees']} trees, {stats['tufts']} tufts, "
          f"{dstats['calls']} radio calls (~{dstats['words']} words), {mstats['pieces']} pieces of music "
          f"({mstats['seconds'] / 60:.1f} min), {len(changed)} file(s) updated")


if __name__ == "__main__":
    main()
